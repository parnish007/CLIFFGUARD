"""Adversarial prompt corpus loaders — see blueprint §12.6.

Fold B provides the adversarial evaluation corpus. Prompts are grouped
by adversary class (A1–A9) and by quantization scheme. The loaders
return structured AttackPrompt records — not raw strings — so that
the evaluation harness can track adversary class, scheme, and expected
outcome alongside each prompt.

Sources per blueprint §12.6:
  A1/A2/A3/A4: JailbreakBench (Chao et al., arXiv:2404.01318)
  A5:          AdvBench (Zou et al., arXiv:2307.15043)
  A6:          ArtPrompt (Ying et al., arXiv:2402.11753)
  A7:          Synthetic cliff-exploiter prompts (generated by the
               authors using the procedure in §11.3)
  A8:          Defender-aware prompts (generated adversarially against
               the calibrated bandit weights)
  A9:          DAN-transfer prompts targeting closed-weight endpoints

In Phase A, loaders operate on synthetic in-memory AttackPrompt
records. Phase B wires them to real JSONL corpus files in data/.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from cliffguard.types import QuantScheme, ThreatModel


@dataclass
class AttackPrompt:
    """A single adversarial prompt record."""

    text: str
    adversary: ThreatModel
    scheme: QuantScheme
    expected_blocked: bool = True
    metadata: dict[str, str] = field(default_factory=dict)


def load_attack_jsonl(
    path: Path,
) -> list[AttackPrompt]:
    """Load AttackPrompt records from a JSONL file.
    Each line must have fields: text, adversary, scheme.
    Optional fields: expected_blocked (default True), metadata (default {}).
    adversary is a ThreatModel enum name (e.g. "A1").
    scheme is a QuantScheme enum name (e.g. "GGUF_Q3_K_M").
    Raises FileNotFoundError if path does not exist.
    Raises ValueError if a line is malformed or enum name is invalid."""
    if not path.exists():
        raise FileNotFoundError(f"Attack corpus file not found: {path}")
    records: list[AttackPrompt] = []
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        raw = raw.strip()
        if not raw:
            continue
        try:
            obj = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise ValueError(
                f"Invalid JSON on line {lineno} of {path}: {exc}"
            ) from exc
        for required in ("text", "adversary", "scheme"):
            if required not in obj:
                raise ValueError(
                    f"Missing required field '{required}' on line {lineno} of {path}"
                )
        try:
            adversary = ThreatModel(obj["adversary"])
        except ValueError as exc:
            raise ValueError(
                f"Unknown adversary name '{obj['adversary']}' on line {lineno}: "
                f"must be one of {[m.value for m in ThreatModel]}"
            ) from exc
        try:
            scheme = QuantScheme[obj["scheme"]]
        except KeyError as exc:
            raise ValueError(
                f"Unknown scheme name '{obj['scheme']}' on line {lineno}: "
                f"must be one of {[s.name for s in QuantScheme]}"
            ) from exc
        records.append(
            AttackPrompt(
                text=str(obj["text"]),
                adversary=adversary,
                scheme=scheme,
                expected_blocked=bool(obj.get("expected_blocked", True)),
                metadata={str(k): str(v) for k, v in obj.get("metadata", {}).items()},
            )
        )
    return records


def filter_by_adversary(
    prompts: list[AttackPrompt],
    adversary: ThreatModel,
) -> list[AttackPrompt]:
    """Return prompts matching the given adversary class."""
    return [p for p in prompts if p.adversary == adversary]


def filter_by_scheme(
    prompts: list[AttackPrompt],
    scheme: QuantScheme,
) -> list[AttackPrompt]:
    """Return prompts matching the given quantization scheme."""
    return [p for p in prompts if p.scheme == scheme]


def make_synthetic_attack_corpus(
    n_per_adversary: int = 10,
    schemes: list[QuantScheme] | None = None,
) -> list[AttackPrompt]:
    """Generate a synthetic attack corpus with n_per_adversary prompts
    per adversary class (A1–A9) per scheme.
    If schemes is None, use [QuantScheme.FP16, QuantScheme.GGUF_Q3_K_M].
    Returns a flat list of AttackPrompt records.
    All expected_blocked = True."""
    if schemes is None:
        schemes = [QuantScheme.FP16, QuantScheme.GGUF_Q3_K_M]
    corpus: list[AttackPrompt] = []
    for adversary in ThreatModel:
        for scheme in schemes:
            for i in range(n_per_adversary):
                corpus.append(
                    AttackPrompt(
                        text=(
                            f"Synthetic {adversary.value} attack prompt #{i} "
                            f"for scheme {scheme.name}"
                        ),
                        adversary=adversary,
                        scheme=scheme,
                        expected_blocked=True,
                    )
                )
    return corpus
